export function allHomeTips() {
    return Object.values(HOME_TIPS).flat();
}

function seed(text) {
    let h = 0;
    for (const ch of String(text)) h = (h * 31 + ch.codePointAt(0)) >>> 0;
    return h;
}

/** 지금 상황에 맞는 묶음을 고르고, 날짜로 그 안의 한 줄을 돌립니다. */
export function pickHomeTip({ ymd = '', hm = '', checked = false, left = 0, off = false, weekday = -1 } = {}) {
    let group;
    const minutes = /^\d{2}:\d{2}$/.test(hm) ? Number(hm.slice(0, 2)) * 60 + Number(hm.slice(3)) : 0;
    if (off) group = 'rest';
    else if (!checked && minutes < 14 * 60) group = 'attend';
    else if (weekday === 5) group = 'friday';
    else if (weekday === 1 && minutes < 12 * 60) group = 'monday';
    else if (left > 0 && minutes >= 12 * 60) group = 'todo';
    else if (minutes < 12 * 60) group = 'morning';
    else if (minutes < 16 * 60 + 30) group = 'afternoon';
    else group = 'evening';
    const list = HOME_TIPS[group];
    return { group, text: list[seed(`${ymd}|${group}`) % list.length] };
}
